<?php

declare(strict_types=1);

namespace Drupal\Tests\canvas\Kernel;

// @phpstan-ignore-next-line (class exists on implementation branch)
use Drupal\canvas\DefaultLanguageChangeHandler;
use Drupal\canvas\Entity\Page;
use Drupal\language\Entity\ConfigurableLanguage;
use Drupal\pathauto\Entity\PathautoPattern;
use Drupal\Tests\user\Traits\UserCreationTrait;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;

/**
 * Tests DefaultLanguageChangeHandler for URL alias regeneration via Pathauto.
 *
 * Covers behavior after the site's default language changes:
 *
 * AC7: URL aliases using language tokens in Pathauto patterns must be
 *      regenerated for all Canvas pages after a default language change.
 *
 * Note: These tests skip gracefully if the `pathauto` module is not installed.
 * Unlike the normal Canvas page presave behavior (which suppresses Pathauto
 * auto-generation because it is managed via the UI), the default language
 * change operation invokes Pathauto regeneration programmatically — bypassing
 * the suppression — because the URL patterns may embed language tokens that
 * are now stale.
 *
 * @see \Drupal\canvas\Hook\PageHooks::ensurePathautoSkipped()
 */
#[RunTestsInSeparateProcesses]
#[CoversClass(DefaultLanguageChangeHandler::class)]
#[Group('canvas')]
#[Group('canvas_translation')]
final class DefaultLanguageChangePathautoTest extends CanvasKernelTestBase {

  use UserCreationTrait;

  /**
   * {@inheritdoc}
   */
  protected static $modules = [
    'language',
    'pathauto',
    'token',
    'canvas_test_pathauto',
  ];

  /**
   * {@inheritdoc}
   */
  protected function setUp(): void {
    parent::setUp();
    $this->installEntitySchema('canvas_page');
    $this->installEntitySchema('path_alias');
    $this->installEntitySchema('pathauto_pattern');
    $this->installEntitySchema('user');
    $this->installConfig(['language', 'pathauto', 'user']);
    $this->config('system.theme')->set('default', 'stark')->save();

    if (!$this->container->get('module_handler')->moduleExists('pathauto')) {
      $this->markTestSkipped('The pathauto module is not installed. Skipping AC7 Pathauto tests.');
    }

    // Pathauto's pattern query uses accessCheck(TRUE); set the current user to
    // one with the 'administer pathauto' permission so patterns are found.
    $admin = $this->createUser(['administer pathauto']);
    \assert($admin !== FALSE);
    $this->setCurrentUser($admin);

    ConfigurableLanguage::createFromLangcode('fr')->save();

    // Create a Pathauto pattern using a simple ID token provided by
    // canvas_test_pathauto, ensuring token resolution always succeeds.
    PathautoPattern::create([
      'id' => 'canvas_page',
      'type' => 'canonical_entities:canvas_page',
      'pattern' => '/pages/[canvas_page:id]',
      'weight' => -10,
    ])->save();
  }

  /**
   * Changes the site's default language by saving system.site config.
   */
  private function changeDefaultLanguageTo(string $new_langcode): void {
    $this->config('system.site')->set('default_langcode', $new_langcode)->save();
  }

  // ---------------------------------------------------------------------------
  // AC7: Pathauto alias regeneration for Canvas pages
  // ---------------------------------------------------------------------------

  /**
   * Tests that a Canvas page's URL alias is regenerated after a language change.
   *
   * Verifies this even though Canvas normally suppresses Pathauto on presave.
   *
   * AC7: URL aliases using language tokens in Pathauto patterns must be
   * regenerated for all content after a default language change.
   *
   * The key difference from the normal presave behavior: the default language
   * change handler bypasses the PathautoState::SKIP suppression so that
   * language-token-based patterns (e.g. [node:language:langcode]/[node:title])
   * are re-evaluated against the new default langcode.
   */
  public function testCanvasPageAliasIsRegeneratedAfterLanguageChange(): void {
    $alias_storage = $this->container->get('entity_type.manager')->getStorage('path_alias');

    $page = Page::create([
      'title' => 'My Canvas Page',
      'langcode' => 'en',
      'status' => TRUE,
      'path' => [['alias' => '/my-canvas-page']],
      'components' => [],
    ]);
    $page->save();

    $this->changeDefaultLanguageTo('fr');

    // After the language change, a new FR alias must have been generated by
    // Pathauto (programmatically, bypassing the usual suppression).
    $fr_aliases = $alias_storage->loadByProperties([
      'path' => '/page/' . $page->id(),
      'langcode' => 'fr',
    ]);
    self::assertNotEmpty($fr_aliases, 'A new FR alias must exist after the language change regeneration.');

    // The new alias must match the Pathauto pattern.
    $fr_alias = reset($fr_aliases);
    self::assertSame(
      '/pages/' . $page->id(),
      $fr_alias->getAlias(),
      'Regenerated alias must match the Pathauto pattern.'
    );
  }

  /**
   * Tests that alias regeneration does not create duplicate aliases.
   *
   * AC7: Aliases must be regenerated cleanly — re-running must not create
   * duplicate entries for the same path.
   */
  public function testAliasRegenerationDoesNotCreateDuplicates(): void {
    $alias_storage = $this->container->get('entity_type.manager')->getStorage('path_alias');

    $page = Page::create([
      'title' => 'Unique Page',
      'langcode' => 'en',
      'status' => TRUE,
      'path' => [['alias' => '/unique-page']],
      'components' => [],
    ]);
    $page->save();

    $this->changeDefaultLanguageTo('fr');

    $aliases = $alias_storage->loadByProperties([
      'path' => '/page/' . $page->id(),
    ]);

    // There must be exactly one alias per language, not duplicates.
    $langcodes = \array_map(
      static fn ($alias) => $alias->get('langcode')->value,
      $aliases
    );
    self::assertSame(
      \array_unique($langcodes),
      $langcodes,
      'Alias regeneration must not produce duplicate entries for the same path and language.'
    );
  }

  /**
   * Tests that all Canvas pages have their aliases regenerated, not just one.
   *
   * AC7: URL aliases must be regenerated for ALL content, not just the first
   * Canvas page encountered.
   */
  public function testAllCanvasPageAliasesAreRegenerated(): void {
    $alias_storage = $this->container->get('entity_type.manager')->getStorage('path_alias');

    $page1 = Page::create(['title' => 'Page One', 'langcode' => 'en', 'status' => TRUE, 'components' => []]);
    $page1->save();
    $page2 = Page::create(['title' => 'Page Two', 'langcode' => 'en', 'status' => TRUE, 'components' => []]);
    $page2->save();

    $this->changeDefaultLanguageTo('fr');

    foreach ([$page1->id(), $page2->id()] as $page_id) {
      $aliases = $alias_storage->loadByProperties(['path' => '/page/' . $page_id]);
      self::assertNotEmpty(
        $aliases,
        "Canvas page $page_id must have a regenerated alias after language change."
      );
    }
  }

  /**
   * Tests that a Canvas page with a manually locked alias is still regenerated.
   *
   * Verifies this happens programmatically even though the UI would normally
   * preserve locked aliases.
   *
   * AC7: The default language change bypasses normal Pathauto suppression and
   * must regenerate aliases even for pages where the alias would normally be
   * locked by the UI.
   */
  public function testLockedAliasIsRegeneratedOnLanguageChange(): void {
    $alias_storage = $this->container->get('entity_type.manager')->getStorage('path_alias');

    $page = Page::create([
      'title' => 'Page With Manual Alias',
      'langcode' => 'en',
      'status' => TRUE,
      // A manually set alias, simulating a "locked" alias from the UI.
      'path' => [['alias' => '/manually-set-alias']],
      'components' => [],
    ]);
    $page->save();

    $this->changeDefaultLanguageTo('fr');

    // A new FR alias must have been created by Pathauto for the new default
    // language, proving regeneration ran programmatically for this page.
    $fr_aliases = $alias_storage->loadByProperties([
      'path' => '/page/' . $page->id(),
      'langcode' => 'fr',
    ]);
    self::assertNotEmpty($fr_aliases, 'A new FR alias must exist after language change.');
    $fr_alias = reset($fr_aliases);
    self::assertSame(
      '/pages/' . $page->id(),
      $fr_alias->getAlias(),
      'Regenerated alias must match the Pathauto pattern, not the original locked alias.'
    );
  }

}
